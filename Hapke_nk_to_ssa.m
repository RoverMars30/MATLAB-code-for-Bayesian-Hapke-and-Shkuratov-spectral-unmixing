function ssa = Hapke_nk_to_ssa(wl, n, k, D, isSpherical)
%--------------------------------------------------------------------------
% Hapke_calc_ssa_from_nk:
%   根据折射率 n/k、粒径 D 和粒子形状计算单次散射反照率（SSA）
%
% 输入参数：
%   wl         : 波长 (Nx1)，单位 μm
%   n          : 实部折射率 (Nx1 或常数)
%   k          : 虚部折射率 (Nx1)

%   D          : 粒径，单位 μm
%   isSpherical: 是否球形（1 是，0 否）
%
% 输出参数：
%   ssa        : 单次散射反照率，SSA (Nx1)
%--------------------------------------------------------------------------


    if isSpherical == 0
        S = 0.2 * D;
    else
        % 来源：Hapke 1993, 表面粗糙度修正
        S = (2/3) * (n.^2 - (1./n) .* (n.^2 - 1).^(3/2)) .* D;
    end

    % 表面和内部散射系数（经验公式）
    se = ((n - 1).^2 + k.^2) ./ ((n + 1).^2 + k.^2) + 0.05;
    si = 1.014 - 4 ./ (n .* (n + 1).^2);

    % 吸收系数（α）
    alpha = 4 * pi * n .* k ./ wl;

    % 光透过率 θ
    theta = exp(-alpha .* S);

    % 计算 SSA
    tmp = ((1 - si) .* theta) ./ (1 - si .* theta);
    ssa = se + (1 - se) .* tmp;
end
